// 0xRRGGBBAA
constexpr uint32_t RGBA(uint8_t r, uint8_t g, uint8_t b, uint8_t a = 0xFF) {
    return ((uint32_t)r << 24) | ((uint32_t)g << 16) | ((uint32_t)b << 8) | a;
}

