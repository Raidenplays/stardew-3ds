// A pixel font drawn from a texture atlas, 1:1 (no scaling, so it stays crisp).
// The tables are written by the converter from your own game files.
struct BitmapFont {
    std::string tex;
    int height = 0, line = 0;
    struct Glyph { int16_t x = -1, y = 0, w = 0; };
    Glyph glyph[256];
    bool ok() const { return height > 0 && !tex.empty(); }
};

// UTF-8 -> Latin-1 code points (anything else becomes '?').
inline int nextCodepoint(const std::string& s, size_t& i) {
    unsigned char c = (unsigned char)s[i++];
    if (c < 0x80) return c;
    int extra = (c & 0xE0) == 0xC0 ? 1 : (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : 0;
    int cp = c & (0x3F >> extra);
    for (int k = 0; k < extra && i < s.size(); k++) cp = (cp << 6) | ((unsigned char)s[i++] & 0x3F);
    return cp < 256 ? cp : '?';
}

// A texture name passed without copying: string literals ("TerrainFeatures_hoeDirt")
// would otherwise allocate a std::string on every draw call.
struct TexName {
    const char* p;
    size_t n;
    TexName(const char* s) : p(s), n(strlen(s)) {}
    TexName(const std::string& s) : p(s.data()), n(s.size()) {}
    bool operator==(const std::string& s) const { return s.size() == n && memcmp(s.data(), p, n) == 0; }
    std::string str() const { return std::string(p, n); }
    operator std::string() const { return str(); }
};

class Canvas {
public:
    virtual ~Canvas() {}

    // Draw (sx,sy,sw,sh) of texture `tex` (a name under tex/) at (dx,dy).
    // tint != 0 multiplies the texture colour by it.
    // Fast path for drawing lots of tiles from a few sheets: look each sheet
    // up once (texLookup), then draw by handle. Canvases without it fall back
    // to image().
    virtual const void* texLookup(TexName) { return nullptr; }
    virtual void imageTex(const void* handle, TexName tex, int sx, int sy, int sw, int sh, float dx, float dy) {
        (void)handle;
        image(tex, sx, sy, sw, sh, dx, dy);
    }
    virtual void image(TexName tex, int sx, int sy, int sw, int sh, float dx, float dy,
                       bool flipX = false, uint32_t tint = 0) = 0;
    // Rotated draw: the source pixel (px, py) inside the (sx,sy,sw,sh) rect lands on
    // (dx, dy), and the image is turned by `radians` around it (clockwise).
    virtual void imageRotated(TexName tex, int sx, int sy, int sw, int sh, float px, float py,
                              float dx, float dy, float radians, uint32_t tint = 0) = 0;
    // Whole-number scaling (2x, 3x) stays sharp: used for the farmer preview.
    virtual void imageScaled(TexName tex, int sx, int sy, int sw, int sh, float dx, float dy,
                             float scale, bool flipX = false, uint32_t tint = 0) = 0;
    virtual void rect(float x, float y, float w, float h, uint32_t color) = 0;
    virtual void line(float x1, float y1, float x2, float y2, uint32_t color, float width) = 0;
    // scale 0.5 is roughly a 15px-tall line, like the 3DS system font
    virtual void text(float x, float y, float scale, uint32_t color, const std::string& s,
                      int align = ALIGN_LEFT) = 0;
    virtual float textWidth(const std::string& s, float scale) = 0;
    virtual int texWidth(TexName tex) = 0;   // 0 if missing
    virtual int texHeight(TexName tex) = 0;  // 0 if missing
    virtual void dropTextures() = 0;                    // free everything (map/season change)
    // Map cache: a 512x512 offscreen image the still map layers are drawn into
    // once, then shown as one picture instead of hundreds of tiles a frame.
    static constexpr int CACHE_SIZE = 512;
    bool cacheFlipY = false;        // show it upside down (in case the GPU stores it that way)
    virtual bool cacheSupported() { return false; }
    virtual void cacheBegin() {}    // draws go into the (cleared, see-through) cache...
    virtual void cacheEnd() {}      // ...until this, back to the screen
    virtual void cacheDraw(int sx, int sy, int sw, int sh, float dx, float dy) { (void)sx; (void)sy; (void)sw; (void)sh; (void)dx; (void)dy; }

    // Game fonts (set by loadUiFonts); backends use them when loaded.
    BitmapFont fontSmall, fontBold;
    const BitmapFont* fontFor(float scale) const {
        if (scale >= 0.55f && fontBold.ok()) return &fontBold;
        if (fontSmall.ok()) return &fontSmall;
        return nullptr;
    }
    float bitmapWidth(const BitmapFont& f, const std::string& s) const {
        float w = 0;
        for (size_t i = 0; i < s.size();) {
            const BitmapFont::Glyph& g = f.glyph[nextCodepoint(s, i)];
            w += (g.x >= 0 ? g.w : f.glyph['?'].w) + (&f == &fontBold ? 1 : 0);
        }
        return w;
    }
    void bitmapText(const BitmapFont& f, float x, float y, float scale, uint32_t color, const std::string& s,
                    int align) {
        float w = bitmapWidth(f, s);
        if (align == ALIGN_CENTER) x -= w / 2;
        else if (align == ALIGN_RIGHT) x -= w;
        x = (float)(int)(x + 0.5f);
        // keep roughly where the old scaled font sat vertically
        float want = scale * 30.0f;
        y = (float)(int)(y + (want > f.height ? (want - f.height) / 2 : 0) + 0.5f);
        bool tint = &f != &fontBold;   // the bold font has its own colours
        for (size_t i = 0; i < s.size();) {
            int cp = nextCodepoint(s, i);
            const BitmapFont::Glyph* g = &f.glyph[cp];
            if (g->x < 0) g = &f.glyph['?'];
            if (g->x >= 0 && cp != ' ') image(f.tex, g->x, g->y, g->w, f.height, x, y, false, tint ? color : 0);
            x += g->w + (&f == &fontBold ? 1 : 0);
        }
    }

    // Tiny text (scale below ~0.41) uses PIXEL_FONT when the game fonts are on.
    bool pixelTiny() const { return fontSmall.ok(); }
    static void pixelSpan(int code, int& lo, int& hi) {
        lo = 5; hi = -1;
        if (code < 33 || code > 126) return;
        for (int r = 0; r < 7; r++)
            for (int b = 0; b < 5; b++)
                if (PIXEL_FONT[code - 32][r] & (0x10 >> b)) { lo = std::min(lo, b); hi = std::max(hi, b); }
    }
    float pixelWidth(const std::string& s) const {
        float w = 0;
        for (size_t i = 0; i < s.size();) {
            int cp = nextCodepoint(s, i), lo, hi;
            pixelSpan(cp, lo, hi);
            w += hi < 0 ? 3 : hi - lo + 2;
        }
        return w > 0 ? w - 1 : 0;
    }
    void pixelText(float x, float y, float scale, uint32_t color, const std::string& s, int align) {
        float w = pixelWidth(s);
        if (align == ALIGN_CENTER) x -= w / 2;
        else if (align == ALIGN_RIGHT) x -= w;
        int ix = (int)(x + 0.5f);
        int iy = (int)(y + (scale * 30.0f - 7) / 2 + 0.5f);
        for (size_t i = 0; i < s.size();) {
            int cp = nextCodepoint(s, i), lo, hi;
            pixelSpan(cp, lo, hi);
            if (hi < 0) { ix += 3; continue; }
            for (int r = 0; r < 7; r++) {   // one rect per horizontal run
                uint8_t bits = PIXEL_FONT[cp - 32][r];
                for (int b = lo; b <= hi;) {
                    if (!(bits & (0x10 >> b))) { b++; continue; }
                    int e = b;
                    while (e + 1 <= hi && (bits & (0x10 >> (e + 1)))) e++;
                    rect((float)(ix + b - lo), (float)(iy + r), (float)(e - b + 1), 1, color);
                    b = e + 1;
                }
            }
            ix += hi - lo + 2;
        }
    }

    // Stereo: horizontal shift in px per unit of depth for the eye being drawn.
    float eye = 0.0f;
    float shift(float depth) const { return depth * eye; }
};
